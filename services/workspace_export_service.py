"""
workspace_export_service.py — File export helpers for AI Workspace

Converts text/conversation content to:
  PDF   (reportlab)
  DOCX  (python-docx)
  PPTX  (python-pptx)
  XLSX  (xlsxwriter  — parses markdown tables)
"""

import io
import re
from logging_config import get_logger

logger = get_logger(__name__)


# ─────────────────────────────────────────────────────────────
# PDF
# ─────────────────────────────────────────────────────────────

def generate_pdf(content: str, title: str = "Document") -> bytes:
    """Render Markdown-ish text content into a PDF document using reportlab.

    Recognises ``#``/``##``/``###`` headings, ``-``/``*``/bullet lines, and
    ``1.``-style numbered lines; everything else becomes a plain paragraph.
    Inline ``**bold**``/``*italic*``/`` `code` `` markers are stripped (not
    rendered as formatting) via ``_strip_inline``, and text is XML-escaped
    via ``_esc_xml`` for safe inclusion in reportlab Paragraphs.

    Args:
        content: Raw text/Markdown-ish body to render, one block per line.
        title: Document title, rendered as the first (Title-style) paragraph.

    Returns:
        Raw PDF file bytes.
    """
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import inch
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=letter,
        leftMargin=inch, rightMargin=inch,
        topMargin=inch, bottomMargin=inch,
    )
    styles = getSampleStyleSheet()
    bullet_style = ParagraphStyle(
        "bullet", parent=styles["Normal"],
        leftIndent=16, spaceAfter=2,
    )

    story = [Paragraph(_esc_xml(title), styles["Title"]), Spacer(1, 0.25 * inch)]

    for line in content.split("\n"):
        s = line.strip()
        if not s:
            story.append(Spacer(1, 6))
        elif s.startswith("### "):
            story.append(Paragraph(_esc_xml(s[4:]), styles["Heading3"]))
        elif s.startswith("## "):
            story.append(Paragraph(_esc_xml(s[3:]), styles["Heading2"]))
        elif s.startswith("# "):
            story.append(Paragraph(_esc_xml(s[2:]), styles["Heading1"]))
        elif s.startswith(("- ", "* ", "• ")):
            story.append(Paragraph("• " + _esc_xml(_strip_inline(s[2:])), bullet_style))
        elif re.match(r"^\d+\.\s", s):
            story.append(Paragraph(_esc_xml(_strip_inline(re.sub(r"^\d+\.\s", "", s))), styles["Normal"]))
        else:
            story.append(Paragraph(_esc_xml(_strip_inline(s)), styles["Normal"]))

    doc.build(story)
    return buf.getvalue()



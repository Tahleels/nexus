def generate_docx(content: str, title: str = "Document") -> bytes:
    """Render Markdown-ish text content into a DOCX document using python-docx.

    Same line-based block parsing as ``generate_pdf`` (headings, bullets,
    numbered lists, plain paragraphs), mapped onto Word heading levels and
    the built-in "List Bullet"/"List Number" paragraph styles.

    Args:
        content: Raw text/Markdown-ish body to render, one block per line.
        title: Document title, added as a level-0 (Title) heading.

    Returns:
        Raw DOCX file bytes.
    """
    from docx import Document as DocxDocument

    doc = DocxDocument()
    doc.add_heading(title, 0)

    for line in content.split("\n"):
        s = line.strip()
        if not s:
            doc.add_paragraph()
        elif s.startswith("### "):
            doc.add_heading(_strip_inline(s[4:]), 3)
        elif s.startswith("## "):
            doc.add_heading(_strip_inline(s[3:]), 2)
        elif s.startswith("# "):
            doc.add_heading(_strip_inline(s[2:]), 1)
        elif s.startswith(("- ", "* ", "• ")):
            doc.add_paragraph(_strip_inline(s[2:]), style="List Bullet")
        elif re.match(r"^\d+\.\s", s):
            doc.add_paragraph(_strip_inline(re.sub(r"^\d+\.\s", "", s)), style="List Number")
        else:
            doc.add_paragraph(_strip_inline(s))

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()



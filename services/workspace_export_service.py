def generate_pptx(content: str, title: str = "Presentation") -> bytes:
    """Render text content into a PPTX slide deck using python-pptx.

    Builds a title slide ("Generated by AI Workspace" subtitle) followed by
    one "Title and Content" slide per section parsed by ``_parse_slides``
    (sections are split on ``#``/``##`` headings). If no headings are found,
    falls back to a single slide titled ``title`` with up to 20 lines of
    content as bullet points. Each slide is capped at 12 bullet points
    (100 chars for the title, 200 chars per bullet).

    Args:
        content: Raw text/Markdown-ish body to convert into slides.
        title: Title used for the title slide and as the fallback slide title.

    Returns:
        Raw PPTX file bytes.
    """
    from pptx import Presentation

    prs = Presentation()

    # Title slide
    ts = prs.slides.add_slide(prs.slide_layouts[0])
    ts.shapes.title.text = title
    try:
        ts.placeholders[1].text = "Generated by AI Workspace"
    except Exception:
        pass

    slides_data = _parse_slides(content)
    if not slides_data:
        slides_data = [{"title": title,
                        "points": [l.strip() for l in content.split("\n") if l.strip()][:20]}]

    layout = prs.slide_layouts[1]  # Title and Content
    for sd in slides_data:
        slide = prs.slides.add_slide(layout)
        slide.shapes.title.text = sd["title"][:100]
        tf = slide.placeholders[1].text_frame
        tf.word_wrap = True
        tf.clear()
        for i, pt in enumerate(sd["points"][:12]):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.text = pt[:200]
            p.level = 0

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()


def _parse_slides(content: str) -> list:
    """Split Markdown-ish content into slide dicts on ``#``/``##`` headings.

    Args:
        content: Raw text with optional ``#``/``##`` heading lines marking
            slide boundaries; non-heading, non-empty lines under a heading
            become bullet points (leading ``-``/``*``/bullet markers and
            inline formatting are stripped via ``_strip_inline``).

    Returns:
        List of ``{"title": str, "points": list[str]}`` dicts, one per
        heading found. Empty list if no headings are present.
    """
    slides, current = [], None
    for line in content.split("\n"):
        s = line.strip()
        if s.startswith("## ") or s.startswith("# "):
            if current:
                slides.append(current)
            current = {"title": s.lstrip("#").strip(), "points": []}
        elif current is not None and s:
            clean = _strip_inline(s.lstrip("-*• ").strip())
            if clean:
                current["points"].append(clean)
    if current:
        slides.append(current)
    return slides



def generate_xlsx(content: str, title: str = "Data") -> bytes:
    """Render content into an XLSX workbook using xlsxwriter.

    If ``content`` contains a Markdown pipe table (parsed by
    ``_parse_md_table``), each row becomes a worksheet row with the first
    row styled as a header; otherwise each line of ``content`` is written
    verbatim into column A.

    Args:
        content: Raw text, ideally containing a Markdown table (``| a | b |``
            rows, with a ``|---|---|`` divider row skipped automatically).
        title: Worksheet name (truncated to Excel's 31-character limit).

    Returns:
        Raw XLSX file bytes.
    """
    import xlsxwriter

    buf = io.BytesIO()
    wb = xlsxwriter.Workbook(buf, {"in_memory": True})
    ws = wb.add_worksheet(title[:31])

    hdr_fmt  = wb.add_format({"bold": True, "bg_color": "#4f46e5", "font_color": "#ffffff", "border": 1})
    cell_fmt = wb.add_format({"text_wrap": True, "valign": "top", "border": 1})

    rows = _parse_md_table(content)
    if rows:
        for r, row in enumerate(rows):
            for c, cell in enumerate(row):
                ws.write(r, c, cell, hdr_fmt if r == 0 else cell_fmt)
        ws.set_column(0, max(len(r) for r in rows) - 1, 22)
    else:
        for r, line in enumerate(content.split("\n")):
            ws.write(r, 0, line.rstrip())
        ws.set_column(0, 0, 80)

    wb.close()
    return buf.getvalue()


def _parse_md_table(content: str) -> list:
    """Parse Markdown pipe-table rows out of free-form text content.

    Args:
        content: Raw text that may contain lines of the form ``| a | b |``.
            Divider rows (cells matching ``^[-:]+$``, e.g. ``|---|---|``)
            are skipped. Cell text has inline Markdown formatting stripped
            via ``_strip_inline``.

    Returns:
        List of rows, each a list of cell strings. Empty list if no pipe
        table rows are found.
    """
    rows = []
    for line in content.split("\n"):
        s = line.strip()
        if s.startswith("|") and s.endswith("|"):
            cells = [c.strip() for c in s[1:-1].split("|")]
            if any(re.match(r"^[-:]+$", c) for c in cells):
                continue  # skip divider row
            rows.append([_strip_inline(c) for c in cells])
    return rows


# ─────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────

def _strip_inline(text: str) -> str:
    """Strip inline Markdown emphasis/code markers (**bold**, *italic*, `code`, etc.), returning plain text."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"__(.+?)__",     r"\1", text)
    text = re.sub(r"\*(.+?)\*",     r"\1", text)
    text = re.sub(r"_(.+?)_",       r"\1", text)
    text = re.sub(r"`(.+?)`",       r"\1", text)
    return text.strip()


def _esc_xml(text: str) -> str:
    """Escape &, <, > for safe inclusion in reportlab Paragraph XML-ish markup."""
    return (text
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;"))
